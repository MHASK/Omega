import {mkdir,copyFile,rm,cp} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.dirname(fileURLToPath(import.meta.url)),out=path.join(root,'dist');
await rm(out,{recursive:true,force:true});
await mkdir(path.join(out,'assets'),{recursive:true});
for(const name of ['index.html','site.css','site.js','robots.txt','sitemap.xml','sky.svg'])await copyFile(path.join(root,name),path.join(out,name));
await copyFile(path.join(root,'../Omega-Icon.png'),path.join(out,'assets/omega.png'));
await cp(path.join(root,'screenshots'),path.join(out,'assets/screenshots'),{recursive:true});
console.log(`Built ${out}`);
